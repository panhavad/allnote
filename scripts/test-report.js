#!/usr/bin/env node
// Runs every test suite plus a dependency audit and saves the results inside the project:
//   test/reports/latest.md   human-readable report (overwritten each run)
//   test/reports/latest.txt  raw test output
//   test/reports/history.md  one line per run
//   README.md                test summary between the test-summary markers
// Usage: npm run test:report
import { spawnSync, execSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const ROOT = path.join(import.meta.dirname, '..');
const REPORTS = path.join(ROOT, 'test', 'reports');
fs.mkdirSync(REPORTS, { recursive: true });

const SUITES = {
  'api.test.js': 'Core features (auth, 2FA, notes, sharing, publishing, Google SSO)',
  'admin.test.js': 'Administration, approval, expiration, licenses, landing page, tour, versioning',
  'security.test.js': 'Security (access control, locked accounts, brute force, CSRF, headers, secrets, validation)',
  'migration.test.js': 'Backward compatibility (v1.0 database upgrade)',
  'ui.test.js': 'UI guarantees (no emoji, icons, light/dark mode, version display)',
};

const sh = (cmd) => {
  try { return execSync(cmd, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { return ''; }
};
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const started = new Date();
const commit = sh('git rev-parse --short HEAD') || 'n/a';
const dirty = sh('git status --porcelain') ? ' (with uncommitted changes)' : '';

const results = [];
let raw = '';
for (const file of fs.readdirSync(path.join(ROOT, 'test')).filter((f) => f.endsWith('.test.js')).sort()) {
  const run = spawnSync(process.execPath, ['--disable-warning=ExperimentalWarning', '--test', '--test-reporter=spec', path.join('test', file)], {
    cwd: ROOT, encoding: 'utf8', env: { ...process.env, FORCE_COLOR: '0', NO_COLOR: '1' },
  });
  const out = `${run.stdout}${run.stderr}`.replace(/\x1b\[[0-9;]*m/g, '');
  raw += `===== ${file} =====\n${out}\n`;
  const tests = [...out.matchAll(/^([\u2714\u2716]) (.+?) \(([\d.]+)ms\)$/gm)].map((m) => ({ ok: m[1] === '\u2714', name: m[2], ms: Number(m[3]) }));
  const num = (k) => Number(new RegExp(`^\\u2139 ${k} ([\\d.]+)`, 'm').exec(out)?.[1] || 0);
  const failed = num('fail') || (run.status ? 1 : 0);
  results.push({ file, title: SUITES[file] || file, tests, pass: num('pass'), fail: failed, ms: num('duration_ms') });
}

// Dependency vulnerability scan (production dependencies only).
let audit = { ok: false, text: 'npm audit could not run (offline?)' };
try {
  const r = spawnSync('npm audit --omit=dev --json', { cwd: ROOT, encoding: 'utf8', shell: true });
  const j = JSON.parse(r.stdout);
  const v = j.metadata?.vulnerabilities || {};
  const total = Object.values(v).reduce((a, b) => a + b, 0);
  audit = {
    ok: total === 0,
    text: total === 0 ? 'no known vulnerabilities in production dependencies'
      : `${total} vulnerabilities (${Object.entries(v).filter(([, n]) => n).map(([k, n]) => `${n} ${k}`).join(', ')})`,
  };
} catch { /* keep default */ }

const pass = results.reduce((a, r) => a + r.pass, 0);
const fail = results.reduce((a, r) => a + r.fail, 0);
const secSuite = results.find((r) => r.file === 'security.test.js');
const stamp = `${started.toISOString().replace('T', ' ').slice(0, 16)} UTC`;
const status = fail ? 'FAILED' : 'PASSED';

const summaryTable = [
  '| Suite | Tests | Passed | Failed | Time |',
  '| --- | ---: | ---: | ---: | ---: |',
  ...results.map((r) => `| ${r.title} | ${r.pass + r.fail} | ${r.pass} | ${r.fail} | ${(r.ms / 1000).toFixed(1)} s |`),
  `| **Total** | **${pass + fail}** | **${pass}** | **${fail}** | |`,
].join('\n');

const md = `# Test report

- **Result:** ${status}, ${pass} of ${pass + fail} tests passed
- **Date:** ${stamp}
- **Version:** ${pkg.version}, commit \`${commit}\`${dirty}
- **Environment:** Node ${process.version}, ${os.type()} ${os.release()} (${os.arch()})
- **Dependency audit:** ${audit.text}

Generated by \`npm run test:report\`. Raw output: [latest.txt](latest.txt). Previous runs: [history.md](history.md).

## Summary

${summaryTable}

## Security testing

${secSuite ? `${secSuite.pass} of ${secSuite.pass + secSuite.fail} security tests passed` : 'Security suite missing'}; dependency audit: ${audit.text}.

${results.map((r) => `## ${r.title}\n\n\`test/${r.file}\`\n\n| Result | Test | Time |\n| --- | --- | ---: |\n${r.tests.map((t) => `| ${t.ok ? 'PASS' : '**FAIL**'} | ${t.name} | ${Math.round(t.ms)} ms |`).join('\n')}`).join('\n\n')}
`;

fs.writeFileSync(path.join(REPORTS, 'latest.md'), md);
fs.writeFileSync(path.join(REPORTS, 'latest.txt'), raw);

const historyFile = path.join(REPORTS, 'history.md');
if (!fs.existsSync(historyFile)) {
  fs.writeFileSync(historyFile, '# Test history\n\n| Date | Version | Commit | Result | Passed | Failed | Dependency audit |\n| --- | --- | --- | --- | ---: | ---: | --- |\n');
}
fs.appendFileSync(historyFile, `| ${stamp} | ${pkg.version} | \`${commit}\`${dirty ? ' +' : ''} | ${status} | ${pass} | ${fail} | ${audit.ok ? 'clean' : audit.text} |\n`);

// Keep the README summary in sync.
const readmePath = path.join(ROOT, 'README.md');
const readme = fs.readFileSync(readmePath, 'utf8');
const START = '<!-- test-summary:start -->';
const END = '<!-- test-summary:end -->';
if (readme.includes(START) && readme.includes(END)) {
  const block = `${START}\n**Last run:** ${stamp}, version ${pkg.version}: **${status}**, ${pass}/${pass + fail} tests passed. Dependency audit: ${audit.text}.\n\n${summaryTable}\n\nFull report: [test/reports/latest.md](test/reports/latest.md)\n${END}`;
  fs.writeFileSync(readmePath, readme.slice(0, readme.indexOf(START)) + block + readme.slice(readme.indexOf(END) + END.length));
}

console.log(`${status}: ${pass}/${pass + fail} tests passed; dependency audit: ${audit.text}.`);
console.log(`Report saved to ${path.relative(ROOT, path.join(REPORTS, 'latest.md'))}`);
process.exit(fail ? 1 : 0);
